"""Prepare the nautical art and measure shores in pixels used by the game."""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parent
PROJECT = ROOT.parents[4]
OUTPUT = PROJECT / 'assets/images/background'
TILE_WIDTH, TILE_HEIGHT = 768, 416
BAND = 80
WORLD_STEP = 8
# Source spans that map to the fixed shore bands. The seawater between them stretches with the viewport.
BANDS = {'vis-luka': (268, 166), 'solta': (268, 273), 'vis-kanal': None}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def boundaries(image, stage):
    pixels = image.filter(ImageFilter.BoxBlur(3)).load()
    top_span, bottom_span = BANDS[stage]
    top, bottom = [], []
    for world_x in range(0, TILE_WIDTH + 1, WORLD_STEP):
        x = min(image.width - 1, world_x * 2)
        if stage == 'solta':
            # The exposed warm limestone contrasts with the blue-green water.
            def rock(y):
                r, _, b = pixels[x, y]
                return r > b - 4 and r > 65
            upper = max(y for y in range(155, 235) if rock(y))
            lower = min(y for y in range(780, 877) if rock(y))
        else:
            # The straight stone quay meets the water at y=196 in the source.
            upper = 196
            lower = next(y for y in range(865, 964) if pixels[x, y][0] > 16)
        top.append(round(upper * BAND / top_span))
        bottom.append(round((image.height - lower) * BAND / bottom_span))
    return {'top': top, 'bottom': bottom}


def resized(image, spans):
    if not spans:
        return image.resize((TILE_WIDTH, TILE_HEIGHT), Image.Resampling.LANCZOS)
    top, bottom = spans
    regions = [(0, top, 0, BAND), (top, image.height - bottom, BAND, TILE_HEIGHT - BAND),
               (image.height - bottom, image.height, TILE_HEIGHT - BAND, TILE_HEIGHT)]
    tile = Image.new('RGB', (TILE_WIDTH, TILE_HEIGHT))
    for y1, y2, dst1, dst2 in regions:
        crop = image.crop((0, y1, image.width, y2))
        tile.paste(crop.resize((TILE_WIDTH, dst2 - dst1), Image.Resampling.LANCZOS), (0, dst1))
    return tile


def main():
    provenance = []
    coastlines = {}
    for stage, spans in BANDS.items():
        path = ROOT / f'{stage}-source.png'
        image = Image.open(path).convert('RGB')
        assert image.size == (1536, 1024)
        coastlines[stage] = boundaries(image, stage) if spans else None
        tile = resized(image, spans).quantize(192, dither=Image.Dither.NONE)
        destination = OUTPUT / f'camac-{stage}.png'
        tile.save(destination, optimize=True)
        provenance.append(dict(id=stage, source=path.name, sourceSize=image.size, sourceSha256=sha(path),
                               output=destination.relative_to(PROJECT).as_posix(), outputSize=tile.size,
                               sha256=sha(destination), sourceBands=spans, hotspots=[]))
    (ROOT / 'assets.json').write_text(json.dumps(provenance, indent=2) + '\n', encoding='utf-8')
    # Use the same profiles for placing the pier, both defenses and the browser preview.
    target = PROJECT / 'scenes/camac/coastlines.js'
    contents = '// Generated by assets/images/sources/pozadine/camac-etape/prepare.py\n'
    contents += f'export const shoreBand = {BAND}\nexport const tileWidth = {TILE_WIDTH}\n'
    contents += f'export const sampleSpacing = {WORLD_STEP}\nexport const coastlines = {{\n'
    for stage, edges in coastlines.items():
        if edges:
            contents += f"  '{stage}': {{\n    top: {edges['top']},\n    bottom: {edges['bottom']},\n  }},\n"
        else:
            contents += f"  '{stage}': null,\n"
    target.write_text(contents + '}\n', encoding='utf-8')


if __name__ == '__main__':
    main()
