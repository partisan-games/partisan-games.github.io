"""Register the chosen frontal enemies and export their common game/story art."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
READY = ROOT / 'assets/images/game-ready/vojnici'
# stride: metres the body covers in one walk cycle as drawn, two heel-to-heel steps at double support measured on the
# walk-left row against the figure's standing height
PROFILES = {
    'rifleman': {'reference': '01-rifleman.png', 'shotInterval': 1.2, 'sound': 'rifle.mp3', 'stride': 1.27},
    'sentry': {'reference': 'winter-sentry-redraw-idle.png', 'shotInterval': 1.2, 'sound': 'rifle.mp3', 'stride': 1.34,
               'allowedSeasons': ['winter']},
}


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def read(path):
    return json.loads(path.read_text(encoding='utf8'))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--only', choices=list(PROFILES))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest_path = HERE / 'animation-sprites.json'
    if args.check:
        data = read(manifest_path)
        for asset in data['assets']:
            assert sha(HERE / asset['source']) == asset['sourceSha256']
            assert sha(HERE / asset['reference']) == asset['referenceSha256']
            path = HERE / asset['image']
            assert sha(path) == asset['sha256']
            image = Image.open(path)
            w, h = asset['frame']['width'], asset['frame']['height']
            assert image.size == (4*w, 6*h)
            if asset.get('idlePixelsUnchanged'):
                assert image.crop((0, 0, w, h)).tobytes() == Image.open(HERE / asset['reference']).convert('RGBA').tobytes()
            for source in asset.get('sources', []):
                assert sha(HERE / source['path']) == source['sha256']
            assert set(image.getchannel('A').get_flattened_data()) == {0, 255}
            for row in range(6):
                for col in range(4):
                    bounds = image.crop((col*w, row*h, (col+1)*w, (row+1)*h)).getbbox()
                    assert bounds and bounds[0] > 0 and bounds[1] > 0 and bounds[2] < w and bounds[3] < h, bounds
                    if row == 5:
                        assert bounds[3] == asset['anchor']['y'], 'Fallen poses must touch their registered ground'
        if (HERE / 'winter-sentry-animation-protected.json').exists():
            import runpy
            protected = runpy.run_path(str(HERE / 'prepare-sentry-animations.py'))['verify_protected']()
            for name, runtime in protected['runtime'].items():
                assert next(a for a in data['assets'] if a['id'] == name)['runtime'] == runtime
        print(f"Checked {len(data['assets'])} animated enemies, complete cells, alpha and source hashes.")
        return
    entries = read(manifest_path)['assets'] if manifest_path.exists() else []
    runtime = {}
    for kind, profile in PROFILES.items():
        if kind == 'sentry':
            if not args.only or args.only == kind:
                import runpy
                asset = runpy.run_path(str(HERE / 'prepare-sentry-animations.py'))['prepare']()
                runtime[kind] = asset['runtime']
                entries = [a for a in entries if a['id'] != asset['id']] + [asset]
                print('Packed animated winter sentry; existing enemies protected.')
            continue
        if kind == 'rifleman' and (not args.only or args.only == kind) and (HERE / 'rifleman-redraw-c-generated.png').exists():
            import runpy
            asset = runpy.run_path(str(HERE / 'prepare-rifleman-redraw.py'))['prepare']()
            runtime[kind] = asset['runtime']
            entries = [a for a in entries if a['id'] != asset['id']] + [asset]
            print('Packed outlined rifleman from three larger sheets; registered size preserved.')
            continue
    for asset in entries:
        runtime.setdefault(asset['id'].removeprefix('otpisani-'), asset['runtime'])
    manifest_path.write_text(json.dumps({'schemaVersion': 1, 'assets': entries}, indent=2)+'\n', encoding='utf8')
    (ROOT / 'core/actor/soldiers/frontEnemyArt.js').write_text('// Generated by enemy-front-variants/prepare-animations.py.\nexport default '
        +json.dumps(runtime, indent=2).replace('"', "'")+'\n', encoding='utf8')
    kinds = {kind: {'shotInterval': profile['shotInterval'], 'sound': profile['sound'], 'stride': profile['stride']}
             for kind, profile in PROFILES.items()}
    for kind, profile in PROFILES.items():
        if 'allowedSeasons' in profile:
            kinds[kind]['allowedSeasons'] = profile['allowedSeasons']
    (ROOT / 'core/gameplay/frontEnemyKinds.js').write_text('// Generated by enemy-front-variants/prepare-animations.py.\nexport default '
        +json.dumps(kinds, indent=2).replace('"', "'")+'\n', encoding='utf8')


if __name__ == '__main__':
    main()
