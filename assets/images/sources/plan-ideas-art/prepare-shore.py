"""Prepare registered sandbags, MG34 and its own crew as separate layers."""
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[3]
READY = ROOT / 'assets/images/game-ready/polozaji'


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    record = HERE / 'shore-redraw.json'
    if args.check:
        data = json.loads(record.read_text(encoding='utf8'))
        for item in [data['source'], *data['outputs']]:
            assert sha(HERE / item['path']) == item['sha256'], item
        print('Shore nest: source, gun registration, crew and outputs verified.')
        return
    path = HERE / 'shore-redraw-generated.png'
    raw = Image.open(path).convert('RGBA')
    raw.putalpha(raw.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
    rows = [0, 300, 590, 790, 1024]
    cells = [raw.crop((0, rows[i], 768, rows[i+1])) for i in range(4)]
    bounds = [cell.getbbox() for cell in cells[:2]]
    box = [min(b[0] for b in bounds), bounds[0][1], max(b[2] for b in bounds), bounds[0][3]]
    sx, sy = 232/(box[2]-box[0]), 88/(box[3]-box[1])
    offset = [4-box[0]*sx, 4-box[1]*sy]
    hulls = []
    for index in range(2):
        # Use the same footprint for intact and ruined bags, only translate row registration.
        dy = 0 if index == 0 else box[1]-cells[index].getbbox()[1]
        transformed = cells[index].transform((240, 96), Image.Transform.AFFINE,
            (1/sx, 0, -offset[0]/sx, 0, 1/sy, -offset[1]/sy-dy), Image.Resampling.NEAREST)
        frame = Image.new('RGBA', transformed.size)
        frame.alpha_composite(transformed)
        hulls.append(frame)
    hulls[0].save(READY / 'mitraljesko-gnezdo-odozgo.png')
    hulls[0].save(HERE / 'shore-mg-damaged-reference.png')
    hulls[1].save(HERE / 'shore-mg-damaged-generated.png')
    # The mount sits on the receiver. The source muzzle and runtime tip coincide exactly.
    pivot, muzzle = [335, 88], [666, 87]
    anchor, tip = [80, 48], [184, 48]
    dx, dy = muzzle[0]-pivot[0], muzzle[1]-pivot[1]
    a = (tip[0]-anchor[0])*dx/(dx*dx+dy*dy)
    b = -(tip[0]-anchor[0])*dy/(dx*dx+dy*dy)
    determinant = a*a+b*b
    tx, ty = anchor[0]-a*pivot[0]+b*pivot[1], anchor[1]-b*pivot[0]-a*pivot[1]
    gun = cells[2].transform((192, 96), Image.Transform.AFFINE,
        (a/determinant, b/determinant, -(a*tx+b*ty)/determinant,
         -b/determinant, a/determinant, (b*tx-a*ty)/determinant), Image.Resampling.NEAREST)
    clean = Image.new('RGBA', gun.size)
    clean.alpha_composite(gun)
    clean.save(READY / 'shore-mg-gun.png')
    crew = Image.new('RGBA', (256, 80))
    for col in range(2):
        source = raw.crop((col*768, 790, (col+1)*768, 1024))
        bounds = source.getbbox()
        scale = .2
        pos = [round(64-(bounds[0]+bounds[2])/2*scale), round(40-(bounds[1]+bounds[3])/2*scale)]
        source = source.resize((round(source.width*scale), round(source.height*scale)), Image.Resampling.NEAREST)
        crew.alpha_composite(source, (col*128+pos[0], pos[1]))
    crew.save(READY / 'shore-mg-crew.png')
    art = {'src': 'game-ready/polozaji/mitraljesko-gnezdo-odozgo.png',
        'gun': {'src': 'game-ready/polozaji/shore-mg-gun.png', 'width': 192, 'height': 96,
                'anchor': {'x': 80, 'y': 48}, 'muzzle': tip, 'clips': {'idle': {'ms': [1000], 'loop': True}}},
        'crew': {'src': 'game-ready/polozaji/shore-mg-crew.png', 'width': 128, 'height': 80,
                 'anchor': {'x': 64, 'y': 40}, 'clips': {'idle': {'ms': [1000], 'loop': True},
                 'dead': {'ms': [1000], 'frameColumns': [1]}}}}
    (ROOT / 'core/actor/artillery/shoreNestArt.js').write_text('// Generated by plan-ideas-art/prepare-shore.py.\nexport default '
        +json.dumps(art, indent=2).replace('"', "'")+'\n', encoding='utf8')
    outputs = [READY / 'mitraljesko-gnezdo-odozgo.png', READY / 'shore-mg-gun.png', READY / 'shore-mg-crew.png',
               HERE / 'shore-mg-damaged-reference.png', HERE / 'shore-mg-damaged-generated.png']
    import os
    tracked = lambda p: {'path': os.path.relpath(p, HERE).replace('\\', '/'), 'sha256': sha(p)}
    data = {'source': tracked(path), 'outputs': [tracked(p) for p in outputs], 'sourceRows': rows,
            'hullScale': [sx, sy], 'hullOffset': offset, 'gunSourcePivot': pivot, 'gunSourceMuzzle': muzzle,
            'gunAnchor': anchor, 'gunMuzzle': tip, 'crewScale': .2, 'generator': 'generation.json'}
    record.write_text(json.dumps(data, indent=2)+'\n', encoding='utf8')
    print('Packed shore nest, damaged bags, registered MG34 and dedicated two-pose crew.')


if __name__ == '__main__':
    main()
