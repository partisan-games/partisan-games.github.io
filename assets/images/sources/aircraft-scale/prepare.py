"""Native top-view aircraft at 40 px/m; uniform downsampling and measured propeller hubs."""
import hashlib
import json
import math
from pathlib import Path
from PIL import Image

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[3]
OUT=ROOT/'assets/images/game-ready/avioni'
generation=json.loads((HERE/'generation.json').read_text(encoding='utf-8'))
records=[]
layers={}
for entry in generation['entries']:
    key=entry['id']
    source=HERE/entry.get('source',key+'-generated.png')
    image=Image.open(source).convert('RGBA')
    image.putalpha(image.getchannel('A').point(lambda a:255 if a>=128 else 0))
    if entry.get('yellowCowling'):
        # Palette variant of the native Bf109 source; preserve alpha, lines, geometry and all pixels outside the cowling.
        for y in range(55,220):
            for x in range(720,817):
                r,g,b,a=image.getpixel((x,y))
                shade=(r+g+b)/3
                if a and shade>40:
                    image.putpixel((x,y),(min(255,round(shade*1.65)),min(220,round(shade*1.3)),round(shade*.25),a))
    box=image.getbbox()
    assert box and all([box[0]>0,box[1]>0,box[2]<image.width,box[3]<image.height]), (key,box,'clipped source')
    width,height=math.ceil(entry['span']*40),math.ceil(entry['length']*40)
    factor=min(width/(box[2]-box[0]),height/(box[3]-box[1]))
    assert factor<=1, (key,'native source too small')
    body=image.crop(box).resize((round((box[2]-box[0])*factor),round((box[3]-box[1])*factor)),Image.Resampling.NEAREST)
    at=((width-body.width)//2,(height-body.height)//2)
    frame=Image.new('RGBA',(width,height))
    frame.paste(body,at)
    name=key if key.endswith('-top') else key+'-top'
    target=OUT/(name+'.png')
    frame.save(target,optimize=True)
    # Native source coordinates measured on the redraw, shared with its propeller overlay.
    hubs=([[580,102,210],[956,102,210]] if key=='bf110' else
          [[597,74,240],[937,74,240]] if key=='he111-top' else
          [[(box[0]+box[2])/2,box[1]+16,(box[2]-box[0])*.29]])
    measured=[dict(x=at[0]+(x-box[0])*factor,y=at[1]+(y-box[1])*factor,span=span*factor) for x,y,span in hubs]
    src=target.relative_to(ROOT/'assets/images').as_posix()
    layers[src]=dict(id=key,bodySize=[width,height],projection='top',hubs=measured,
                    layer=dict(src='game-ready/avioni/propeller-top-sprites.png',frame=dict(width=64,height=12),columns=4,seconds=.12))
    sha=lambda p:hashlib.sha256(p.read_bytes()).hexdigest()
    records.append(dict(id=key,image='../../game-ready/avioni/'+target.name,source=source.name,sourceSha256=sha(source),
                        sha256=sha(target),frame=dict(width=width,height=height,columns=1,rows=1),
                        anchor=dict(x=width/2,y=height/2),animations=[dict(name='idle',row=0,frameCount=1,duration=1,loop=True)],
                        pixelsPerMetre=40,scale=factor,sourceBounds=box,offset=at,propellers=layers[src],
                        derivation=entry.get('derivation')))
(HERE/'sprites.json').write_text(json.dumps(dict(assets=records),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
(ROOT/'core/actor/aircraft/topAircraftArt.js').write_text('// Generated by aircraft-scale/prepare.py.\nexport default '+json.dumps(layers,indent=2).replace('"',"'")+'\n',encoding='utf-8')
print('Prepared native top-view aircraft:',len(records))
