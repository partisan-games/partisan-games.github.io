"""Prepare the seven selected road vehicles from native imagegen sources; never upscale."""
import hashlib
import json
import math
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
OUT = ROOT / 'assets/images/game-ready/vozila'
# Length includes the fixed gun. Unidentified 612 uses a declared Sd.Kfz.231 physical proxy.
MODELS = {
    'zundapp-k600': ('Zündapp K600', 2.15, .8, 1, 20, 5.5, None, [0, 0]),
    'bmw-r12': ('BMW R12 sa prikolicom', 2.1, 1.65, 1, 25, 5, None, [0, 0]),
    'sdkfz-231': ('Sd.Kfz. 231', 5.85, 2.2, -1, 70, 4.8, 'sdkfz-231', [64, 50]),
    'pzkpf-612': ('Pz.Kpfw. 612 (37 mm)', 5.85, 2.2, -1, 75, 4, 'pzkpf-612', [205, 49]),
    'mercedes-830bl': ('Horch 830 BL', 5.05, 1.8, -1, 30, 5, None, [0, 0]),
    'marder-ii': ('Marder II (76 mm)', 6.36, 2.28, -1, 95, 3.5, 'marder-ii', [23, 63]),
    'elefant': ('Elefant', 8.14, 3.38, -1, 180, 2.3, 'elefant', [23, 73]),
}

def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()

art, kinds, records = {}, {}, []
for key, (title, length, width, facing, health, speed, physical, tip) in MODELS.items():
    source = HERE / (key + '-generated.png')
    if not source.exists():
        continue
    raw = Image.open(source).convert('RGBA')
    raw.putalpha(raw.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
    cells = [raw.crop((round(c*raw.width/4), round(r*raw.height/5),
                       round((c+1)*raw.width/4), round((r+1)*raw.height/5))) for r in range(5) for c in range(4)]
    first = cells[0].getbbox()
    factor = math.ceil(length * 40) / (first[2]-first[0])
    assert factor <= 1, (key, 'native source too small', factor)
    height = (first[3]-first[1])*factor / 40
    # One scale for the whole sheet; register ground and horizontal centre, never stretch individual poses.
    boxes = [c.getbbox() for c in cells]
    w = max(round((b[2]-b[0])*factor) for b in boxes)+12
    h = max(round((b[3]-b[1])*factor) for b in boxes)+12
    sheet = Image.new('RGBA', (w*4, h*5))
    transforms = []
    for index, (cell, box) in enumerate(zip(cells, boxes)):
        tile = cell.crop(box).resize((round((box[2]-box[0])*factor), round((box[3]-box[1])*factor)), Image.Resampling.NEAREST)
        at = ((w-tile.width)//2, h-4-tile.height)
        sheet.paste(tile, ((index%4)*w+at[0], (index//4)*h+at[1]))
        transforms.append(dict(sourceBounds=box, offset=at))
    # The last two death poses are the held wreck, never a live crew frame.
    first_out = sheet.crop((0,0,w,h)).getbbox()
    height = (first_out[3]-first_out[1])/40
    target = OUT / (key+'-sprites.png')
    sheet.save(target, optimize=True)
    clips = {name: dict(row=i, ms=[ms]*4, loop=name not in ['attack','dead'])
             for i,(name,ms) in enumerate([('idle',400),('drive',160),('attack',100),('damaged',160),('dead',200)])}
    art[key] = dict(src=target.relative_to(ROOT/'assets/images').as_posix(), width=w,height=h,
                    bounds=first_out,anchor=dict(x=w/2,y=h-4),facing=facing,clips=clips)
    armed = key in ['sdkfz-231','pzkpf-612','marder-ii','elefant']
    muzzle_x = transforms[0]['offset'][0] + (tip[0]-first[0])*factor
    muzzle_y = transforms[0]['offset'][1] + (tip[1]-first[1])*factor
    art[key]['muzzlePoint'] = [muzzle_x,muzzle_y] if armed else None
    kinds[key] = dict(name=title,size=dict(length=length,height=height,width=width),health=health,speed=speed,
                      physicalModel=physical,armed=armed,
                      gun=dict(reload=.35 if key=='sdkfz-231' else 4.5, speed=40,damage=4 if key=='sdkfz-231' else 12,
                               muzzle=dict(ahead=(muzzle_x-(first_out[0]+first_out[2])/2)*length/(first_out[2]-first_out[0])*facing,
                                           above=((first_out[1]+first_out[3])/2-muzzle_y)/40)))
    records.append(dict(id=key,title=title,source=source.name,sourceSha256=sha(source),generation='generation.json',
                        image='../../../game-ready/vozila/'+target.name,sha256=sha(target),
                        frame=dict(width=w,height=h,columns=4,rows=5),anchor=art[key]['anchor'],
                        animations=[dict(name=name,row=c['row'],frameCount=4,duration=sum(c['ms'])/1000,loop=c['loop']) for name,c in clips.items()],
                        pixelsPerMetre=40,scale=factor,cells=transforms,art=art[key]))

def dump(value):
    return json.dumps(value,ensure_ascii=False,indent=2).replace('"',"'")

(ROOT/'core/actor/vehicles/roadVehicleArt.js').write_text('// Generated by road-vehicles/prepare.py.\nexport default '+dump(art)+'\n',encoding='utf-8')
(ROOT/'core/gameplay/roadVehicleProfiles.js').write_text('// Generated by road-vehicles/prepare.py.\nexport default '+dump(kinds)+'\n',encoding='utf-8')
(HERE/'sprites.json').write_text(json.dumps(dict(tool='built-in image_gen',assets=records),ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Prepared road vehicles:',len(records))
