"""Fit single generated wrecks into the unchanged live sprite coordinate systems."""
import hashlib
import json
import re
from pathlib import Path
from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
OUT = ROOT / 'assets/images/armies/game-ready/wrecks'
ALIASES = {
    'partisan-tank': ['armies/game-ready/tenkovi/partizanski-tenk-sprites.png'],
    'german-tank': ['armies/game-ready/tenkovi/nemacki-tenk-sprites.png'],
    'somua-s35': ['armies/game-ready/tenkovi/somua-s35-sprites.png'],
}

def bounds(image):
    return image.getchannel('A').point(lambda a: 255 if a >= 128 else 0).getbbox()

def main():
    OUT.mkdir(exist_ok=True)
    profiles = json.loads((HERE / 'profiles.json').read_text())
    assets, runtime = [], {}
    contact = Image.new('RGB', (900, ((len(profiles) + 2) // 3) * 205), '#58614a')
    pen = ImageDraw.Draw(contact)
    for index, profile in enumerate(profiles):
        key = profile['id']
        source = HERE / (key + '-generated.png')
        if not source.exists():
            continue
        original = Image.open(HERE / profile['reference']).convert('RGBA')
        raw = Image.open(source).convert('RGBA')
        raw.putalpha(raw.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
        crop = raw.crop(bounds(raw))
        left, top, right, bottom = bounds(original)
        scale = min((right - left) / crop.width, (bottom - top) / crop.height)
        crop = crop.resize((max(1, round(crop.width * scale)), max(1, round(crop.height * scale))), Image.Resampling.NEAREST)
        result = Image.new('RGBA', original.size)
        result.alpha_composite(crop, (round((left + right - crop.width) / 2), bottom - crop.height))
        target = OUT / (key + '.png')
        result.save(target)
        width, height = result.size
        descriptor = {'src': 'armies/game-ready/wrecks/' + key + '.png', 'width': width, 'height': height}
        aliases = ALIASES.get(key, [])
        for path in [profile['original'], *aliases, *(p.replace('-sprites.png', '-layers.png') for p in aliases)]:
            runtime[path] = descriptor
        assets.append({'id': key, 'image': '../../game-ready/wrecks/' + key + '.png',
            'frame': {'width': width, 'height': height, 'columns': 1, 'rows': 1},
            'anchor': {'x': width / 2, 'y': bottom}, 'baseline': bottom,
            'source': source.name, 'reference': profile['reference'], 'sourceBounds': list(bounds(raw)),
            'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
            'animations': [{'name': 'dead', 'row': 0, 'frameCount': 1, 'duration': 1, 'loop': False}],
            'integration': profile.get('integration', 'Shared wreck image replaces the live frame only while the same actor is dead; collider, baseline, view transform and reset remain owned by that actor.'),
        })
        if 'prompt' in profile:
            assets[-1].update({'prompt': profile['prompt'],
                'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                'referenceSha256': hashlib.sha256((HERE / profile['reference']).read_bytes()).hexdigest()})
        preview = result.copy()
        preview.thumbnail((290, 170), Image.Resampling.NEAREST)
        x, y = index % 3 * 300, index // 3 * 205
        contact.paste(preview, (x + (300 - preview.width) // 2, y + 200 - preview.height), preview)
        pen.text((x + 5, y + 4), key, fill='white')
    (HERE / 'sprites.json').write_text(json.dumps({'schemaVersion': 1, 'assets': assets}, indent=2) + '\n', encoding='utf-8')
    code = json.dumps(runtime, indent=2)
    code = re.sub(r'"(?:\\.|[^"\\])*"', lambda match: "'" + json.loads(match.group()).replace("'", "\\'") + "'", code)
    (ROOT / 'core/actor/wreckArt.js').write_text('// Generated by assets/images/armies/sources/wrecks/prepare.py.\nexport default ' + code + '\n', encoding='utf-8')
    contact.save(HERE / 'wrecks-game-size.png')
    cards = []
    for profile in profiles:
        key = profile['id']
        if not (OUT / (key + '.png')).exists():
            continue
        details = ('<p>image_gen (built-in): <a href="' + profile['prompt'] + '">prompt</a> · '
            '<a href="' + key + '-generated.png">izvor</a> · '
            '<a href="../../game-ready/wrecks/' + key + '.png">PNG za igru</a></p>') if 'prompt' in profile else ''
        cards.append('<figure id="' + key + '"><img src="../../game-ready/wrecks/' + key + '.png"><figcaption>' + key + details + '</figcaption></figure>')
    (HERE / 'preview.html').write_text('<!doctype html><html lang="sr"><meta charset="utf-8"><title>Olupine</title><style>body{background:#58614a;color:white;font:16px sans-serif}main{display:flex;flex-wrap:wrap}figure{margin:16px}img{image-rendering:pixelated;max-width:576px}figcaption{padding:8px}</style><h1>Olupine — koordinatni sistemi živih aktera</h1><p>Statični završni kadrovi; požar i prelaz daje igra. Isti akteri u postojećem Storybook-u.</p><main>' + ''.join(cards) + '</main></html>', encoding='utf-8')
    print(f'Packed {len(assets)}/{len(profiles)} wrecks, preserving live frame size and ground baseline.')

if __name__ == '__main__':
    main()
