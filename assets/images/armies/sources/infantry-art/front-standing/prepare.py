"""Pack the two original pose sheets per faction at one scale and a fixed boot line."""
from hashlib import sha256
from itertools import groupby
import json
from pathlib import Path
from PIL import Image

here = Path(__file__).resolve().parent
ready = here.parents[2] / 'game-ready' / 'vojnici'
size = (208, 188)
baseline = 186


def poses(path):
    image = Image.open(path).convert('RGBA')
    alpha = image.getchannel('A').point(lambda value: 255 if value >= 128 else 0)
    image.putalpha(alpha)
    columns = alpha.getprojection()[0]
    spans = [list(indices) for opaque, indices in groupby(range(image.width), lambda x: columns[x]) if opaque]
    assert len(spans) == 3
    figures = []
    for span in spans:
        strip = image.crop((span[0], 0, span[-1] + 1, image.height))
        figures.append(strip.crop(strip.getbbox()))
    return figures


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


flash_path = here.parents[3] / 'pucanje.png'
flash = Image.open(flash_path).convert('RGBA').resize((19, 21), Image.Resampling.NEAREST)
manifest = {'cell': size, 'anchor': [104, baseline], 'frames': ['ready', 'knees', 'dead', 'step-wide', 'step-cross', 'step-close', 'fire'],
            'walkCycleMs': 640, 'collapseMs': 750, 'walkPrompt': "Make a clean transparent pixel-art game sheet 3 horizontal isolated full-body stepping poses of ONLY THE FIRST STANDING SOLDIER from the reference. Keep exactly his face, cap, clothes, palette, gun pointed toward viewer, slight breathing shoulders, arms together in AIM, full boots. He is alive in ALL three frames. He side-steps toward screen right facing the viewer, feet push off alternately and cross in front then spread apart. Show three clearly different leg silhouettes at the same scale on common ground line: contact stride feet apart, passing step boots near crossing, rear foot catching up knees flexed. No scenery, no ground or shadows, no borders, no labels, no flashes; transparent background, no kneeling or death poses in this sheet. Three non-touching figures spaced in a single horizontal strip. Match the figure height and the slightly chunky ink pixel art.", 'factions': {}}
manifest.update(schemaVersion=1, assets=[], flash={'source': '../../../../pucanje.png', 'sha256': digest(flash_path)})
for faction in ('nemci', 'cetnici'):
    original = here / (faction + '-generated.png')
    walking = here / (faction + '-walk.png')
    atlas = Image.new('RGBA', (size[0] * 7, size[1]))
    index = 0
    for sheet in (original, walking):
        frames = poses(sheet)
        scale = 180 / frames[0].height
        assert scale <= 1, faction
        for figure in frames:
            sprite = figure.resize((round(figure.width * scale), round(figure.height * scale)), Image.Resampling.NEAREST)
            assert sprite.width <= size[0] and sprite.height <= baseline
            atlas.alpha_composite(sprite, (index * size[0] + (size[0] - sprite.width) // 2, baseline - sprite.height))
            index += 1
    firing = atlas.crop((0, 0, *size))
    firing.alpha_composite(flash, (95, 46 if faction == 'nemci' else 49))
    atlas.alpha_composite(firing, (size[0] * 6, 0))
    output = ready / (faction + '-spreda-celo.png')
    atlas.save(output)
    animations = [
        {'name': name, 'row': 0, 'frameCount': len(columns), 'frameColumns': columns, 'duration': duration, 'loop': loop}
        for name, columns, duration, loop in (
            ('idle', [0], 1, True), ('move', [3, 4, 5, 4], .64, True),
            ('attack', [6, 0], .18, True), ('dead', [0, 1, 2], .75, False))
    ]
    manifest['assets'].append({'id': faction + '-spreda-celo', 'image': '../../../game-ready/vojnici/' + output.name,
                               'frame': {'width': size[0], 'height': size[1], 'columns': 7, 'rows': 1},
                               'anchor': {'x': 104, 'y': baseline}, 'animations': animations})
    manifest['factions'][faction] = {p.name: digest(p) for p in (original, walking, output, here / (faction + '-reference.png'))}
(here / 'sprites.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf8')

(here.parents[5] / 'core/actor/soldiers/frontStandingArt.js').write_text('// Generated by infantry-art/front-standing/prepare.py.\nexport default '+json.dumps({'width':size[0],'height':size[1],'anchor':{'x':size[0]/2,'y':baseline},'standingHeight':180,'pixelsPerMetre':100},indent=2).replace(chr(34),chr(39))+'\n',encoding='utf-8')
