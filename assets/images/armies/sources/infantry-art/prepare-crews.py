"""Pack independent artillery crew layers behind the accepted gun bodies."""
import hashlib
import json
import runpy
from pathlib import Path
from PIL import Image, ImageOps, ImageDraw

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]

def main():
    assets, runtime = [], {}
    previews = HERE / 'previews'
    previews.mkdir(exist_ok=True)
    contact = Image.new('RGBA', (1100, 460), '#58614a')
    pen = ImageDraw.Draw(contact)
    helpers = runpy.run_path(str(HERE.parent / 'tenkovi/prepare.py'))
    for index, (key, body_size, body_offset, cutoff) in enumerate([
        ('flak38', [204, 122], [26, 26], 224), ('pak38', [233, 51], [12, 97], 128),
    ]):
        raw = Image.open(HERE / (key + '-crew-generated.png')).convert('RGBA')
        frames, bounds = [], []
        for row in range(2):
            for col in range(4):
                cell = raw.crop((round(col*raw.width/4), round(row*raw.height/2), round((col+1)*raw.width/4), round((row+1)*raw.height/2)))
                cell.putalpha(cell.getchannel('A').point(lambda a: 255 if a >= cutoff else 0))
                # The first operator must reach toward the mechanism between the men.
                left = cell.crop((0, 0, cell.width//2, cell.height))
                cell.paste(ImageOps.mirror(left), (0, 0))
                frames.append(cell)
                bounds.append(cell.getbbox())
        scale = 74 / max(b[3] - b[1] for b in bounds[:4])
        center = (min(b[0] for b in bounds) + max(b[2] for b in bounds)) / 2
        sheet = Image.new('RGBA', (1024, 320))
        packed = []
        for i, (cell, box) in enumerate(zip(frames, bounds)):
            small = cell.resize((round(cell.width*scale), round(cell.height*scale)), Image.Resampling.NEAREST)
            frame = Image.new('RGBA', (256, 160))
            frame.alpha_composite(small, (round(128-center*scale), round(148-box[3]*scale)))
            sheet.paste(frame, (i%4*256, i//4*160))
            packed.append(frame)
        name = key + '-crew-sprites.png'
        target = ROOT / 'assets/images/game-ready/artiljerija' / name
        sheet.save(target)
        art = {'src': 'game-ready/artiljerija/' + name, 'frame': {'width': 256, 'height': 160},
            'bodySize': body_size, 'bodyOffset': body_offset, 'fireSeconds': .8, 'deathSeconds': .64}
        runtime[key] = art
        assets.append({'id': key + '-crew', 'image': '../../../game-ready/artiljerija/' + name,
            'frame': {'width': 256, 'height': 160, 'columns': 4, 'rows': 2}, 'anchor': {'x': 128, 'y': 148},
            'bodySize': body_size, 'bodyOffset': body_offset, 'source': key + '-crew-generated.png',
            'alphaCutoff': cutoff, 'mirrorFirstOperator': True,
            'sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
            'animations': [{'name': 'idle', 'row': 0, 'frameCount': 1, 'duration': 1.4, 'loop': True},
                {'name': 'fire', 'row': 0, 'frameCount': 4, 'duration': .8, 'loop': False},
                {'name': 'death', 'row': 1, 'frameCount': 4, 'duration': .64, 'loop': False}]})
        for action, row, duration in [('fire', 0, 200), ('death', 1, 160)]:
            helpers['save_gif'](packed[row*4:row*4+4], previews / (key + '-crew-' + action + '.gif'), duration)
        body = Image.open(ROOT / 'assets/images/game-ready/artiljerija' / (key + '-postolje.png')).convert('RGBA')
        for i, frame in enumerate(packed):
            result = frame.copy()
            if i >= 4:
                body = Image.open(ROOT / 'assets/images/game-ready/wrecks' / (key + '.png')).convert('RGBA')
            result.alpha_composite(body, tuple(body_offset))
            x, y = i%4*270, index*230+i//4*108
            show = result.resize((192, 120) if key == 'flak38' else (128, 80), Image.Resampling.NEAREST)
            contact.alpha_composite(show, (x, y+12))
        pen.text((2, index*230), key + ' crew behind base; barrel is separate in game', fill='white')
    (HERE / 'crew-sprites.json').write_text(json.dumps({'schemaVersion': 1, 'assets': assets}, indent=2)+'\n', encoding='utf-8')
    (ROOT / 'core/actor/artillery/crewArt.js').write_text('// Generated by infantry-art/prepare-crews.py.\nexport default '+json.dumps(runtime, indent=2)+'\n', encoding='utf-8')
    contact.convert('RGB').save(previews / 'crews-game-size.png')
    print('Packed Flak and PaK crews: ready, four work phases, four collapse phases; independent of live gun colliders.')

if __name__ == '__main__':
    main()
