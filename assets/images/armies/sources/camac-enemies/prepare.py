"""Package the generated top-down vessels at the existing game's 25 px/m scale.

Only deterministic atlas extraction, uniform scaling and alpha cleanup happen here.
The generated source and prompts remain untouched. No gameplay integration is implied.
"""
import hashlib
import json
from pathlib import Path

from PIL import Image, ImageDraw

HERE = Path(__file__).resolve().parent
PROJECT = HERE.parents[4]
OUT = PROJECT / 'assets/images/armies/game-ready/brodovi'
RECIPES = [
    ('german-launch', (0, 360), 178, 7.1, .99),
    ('german-skiff', (360, 570), 170, 6.75, .93),
    ('german-patrol-vessel', (570, 887), 300, 12, .90),
]


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    source = HERE / 'vessels-generated.png'
    image = Image.open(source).convert('RGBA')
    assert image.size == (1774, 887), image.size
    OUT.mkdir(parents=True, exist_ok=True)
    entries = []
    preview = Image.new('RGB', (700, 410), '#164b59')
    draw = ImageDraw.Draw(preview)
    for row, (name, (top, bottom), length, metres, muzzle) in enumerate(RECIPES):
        figures, boxes = [], []
        for column in range(2):
            cell = image.crop((column * 887, top, (column + 1) * 887, bottom))
            cell.putalpha(cell.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
            box = cell.getbbox()
            assert box and box[0] > 0 and box[2] < 887, (name, column, box)
            figures.append(cell.crop(box))
            boxes.append([column * 887 + box[0], top + box[1], column * 887 + box[2], top + box[3]])
        factor = length / max(figure.width for figure in figures)
        size = (length + 4, round(max(figure.height for figure in figures) * factor) + 4)
        outputs = []
        for column, figure in enumerate(figures):
            scaled = figure.resize((round(figure.width * factor), round(figure.height * factor)), Image.Resampling.LANCZOS)
            scaled.putalpha(scaled.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
            packed = Image.new('RGBA', size)
            packed.paste(scaled, ((size[0] - scaled.width) // 2, (size[1] - scaled.height) // 2))
            suffix = '-wreck' if column else ''
            path = OUT / f'{name}{suffix}.png'
            packed.save(path, optimize=True)
            alpha = packed.getchannel('A')
            assert alpha.getextrema() == (0, 255)
            assert not alpha.crop((0, 0, size[0], 1)).getbbox()
            assert not alpha.crop((0, size[1] - 1, size[0], size[1])).getbbox()
            outputs.append({'src': path.relative_to(PROJECT).as_posix(), 'sha256': digest(path)})
            preview.paste(packed, (20 + column * 350, 35 + row * 120), packed)
        draw.text((20, 15 + row * 120), name, fill='white')
        entries.append({'id': name, 'size': list(size), 'anchor': [size[0] / 2, size[1] / 2],
                        'hullMetres': {'length': metres, 'width': round((size[1] - 4) / 25, 2)},
                        'facing': 1, 'view': 'top-down', 'sourceBounds': boxes,
                        'muzzle': [round(2 + length * muzzle, 1), size[1] / 2],
                        'intact': outputs[0], 'wreck': outputs[1]})
    preview.save(HERE / 'game-size.png')
    manifest = {'source': source.name, 'sourceSize': list(image.size), 'sourceSha256': digest(source),
                'pixelsPerMetre': 25, 'integrated': True, 'entries': entries}
    (HERE / 'sprites.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='utf-8')
    profiles, looks = {}, {}
    for entry in entries:
        profiles[entry['id']] = {'size': {**entry['hullMetres'], 'height': .6},
                                  'muzzle': {'ahead': (entry['muzzle'][0] - entry['anchor'][0]) / 25,
                                             'across': (entry['muzzle'][1] - entry['anchor'][1]) / 25}}
        looks[entry['id']] = {'src': entry['intact']['src'].removeprefix('assets/images/'),
                              'wreck': entry['wreck']['src'].removeprefix('assets/images/'), 'frame': entry['size']}
    for path, data in [('core/gameplay/patrolBoatProfiles.js', profiles), ('core/actor/patrolBoatLooks.js', looks)]:
        (PROJECT / path).write_text('// Generated by armies/sources/camac-enemies/prepare.py\nexport default '
                                    + json.dumps(data, indent=2).replace('"', "'") + '\n', encoding='utf-8')
    print(f'Prepared {len(entries)} vessels and their wrecks and runtime mappings.')


if __name__ == '__main__':
    main()
