"""Export the prepared measurements for shared views; no loading on module import."""
import json
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]
manifest = json.loads((HERE/'sprites.json').read_text(encoding='utf-8-sig'))
jobs = {j['id']:j for j in json.loads((HERE/'jobs.json').read_text(encoding='utf-8-sig'))['jobs']}
art, hits, damage, vessels, profiles, geometry = {}, {}, {}, {}, {}, {}
# Barrel tips measured in the prepared frames, in pixels (not collision-box guesses).
tips = {'rboot':[789,101], 'mfp':[242,34], 'vorpostenboot':[609,81],
        'motorcycle':[74,24], 'sdkfz251':[50,20], 'sdkfz222':[14,19]}
for item in manifest['assets']:
    if item.get('muzzlePoint'): tips[item['id']] = item['muzzlePoint']
    f = item['frame']
    image = Image.open(ROOT/item['repositoryImage']).convert('RGBA')
    rest = image.crop((0,0,f['width'],f['height'])).getbbox()
    desc = dict(src=item['repositoryImage'].removeprefix('assets/images/'),width=f['width'],height=f['height'],
                anchor=item['anchor'],bounds=list(rest),facing=item['facing'],
                clips={c['name']:dict(row=c['row'],ms=[c['duration']*1000/c['frameCount']]*c['frameCount'],
                                      loop=c['loop'],**({'frameColumns':c['frameColumns']} if 'frameColumns' in c else {})) for c in item['animations']})
    if item.get('layers'): desc['layers']=item['layers']
    if item.get('muzzle'): desc['muzzle']=item['muzzle']
    art[item['id']] = desc
    if item['id'] in tips: desc['muzzlePoint']=tips[item['id']]
    if item['kind']=='infantry' and item.get('muzzle'):
        x,y=item['muzzle']['point']
        scale=1.8/(rest[3]-rest[1])
        geometry[item['id']]=dict(ahead=(x-(rest[0]+rest[2])/2)*scale,
                                 above=(rest[3]-y)*scale-.9)
    if item['kind']=='vehicle':
        length,height={'motorcycle':(3.56,2.1),'sdkfz251':(5.8,2.2),'sdkfz222':(4.8,2)}[item['id']]
        sx,sy=length/(rest[2]-rest[0]),height/(rest[3]-rest[1])
        cx,cy=(rest[0]+rest[2])/2,(rest[1]+rest[3])/2
        x,y=tips[item['id']]
        layer = next((layer for layer in item.get('layers', []) if layer['name'] == 'turret'), None)
        if layer:
            mx,my=layer['mount']; ax,ay=layer['anchor']
            geometry[item['id']]=dict(pivot=dict(ahead=(mx-cx)*sx*item['facing'],above=(cy-my)*sy),
                                     barrel=dict(ahead=(x-ax)*sx*item['facing'],above=(ay-y)*sy))
        else:
            geometry[item['id']]=dict(muzzle=dict(ahead=(x-cx)*sx*item['facing'],above=(cy-y)*sy))
    if item['kind'] in ['hit','damage']:
        ref = Image.open(HERE/item['reference']).convert('RGBA')
        desc['referenceSize'] = list(ref.size)
        desc['referenceBounds'] = list(ref.getbbox())
        source = jobs[item['id']]['reference']
        source = source if source.startswith('buildings/') else 'armies/'+source
        if item['id']=='hummel-damaged':
            source='armies/game-ready/tenkovi/hummel-sprites.png'
            desc['offset']=[11,10]
        (hits if item['kind']=='hit' else damage)[source] = item['id']
    if item['kind']=='vessel':
        name = item['id']
        src = desc['src'].replace('-sprites.png','.png')
        vessels[name]=dict(src=src,wreck=src.replace('.png','-wreck.png'),frame=[f['width'],f['height']],crew=item['crew'])
        damage[src]=name+'-damaged'
        for state in ['damaged','heavy']:
            art[name+'-'+state]={**desc,'src':src.replace('.png','-'+state+'.png'),
                                 'clips':{state:dict(row=0,ms=[1600],loop=True)}}
        art[name+'-damaged']['heavy']=name+'-heavy'
        length=item['designLengthMetres']
        profiles[name]=dict(size=dict(length=length,width=(f['height']-8)/25,height=.8),
                            muzzle=dict(ahead=(tips[name][0]-f['width']/2)/25,
                                        across=(tips[name][1]-f['height']/2)/25),
                            gunOffset=3.141592653589793 if name=='mfp' else 0,
                            speed={'rboot':3.2,'mfp':2.2,'vorpostenboot':3.5}[name],
                            health={'rboot':160,'mfp':200,'vorpostenboot':140}[name])

def write(path, source):
    (ROOT/path).write_text('// Generated by armies/sources/plan-ideas-art/export-runtime.py\n'+source+'\n',encoding='utf-8')

dump=lambda data:json.dumps(data,ensure_ascii=False,indent=2).replace('"',"'")
write('core/actor/reinforcementArt.js','export const actorArt = '+dump(art)+'\nexport const hitBySource = '+dump(hits)
      +'\nexport const damageBySource = '+dump(damage)+'\nexport const vesselLooks = '+dump(vessels))
write('core/gameplay/reinforcementVessels.js','export default '+dump(profiles))
write('core/gameplay/reinforcementGeometry.js','export default '+dump(geometry))
print('Exported prepared art and vessel measurements.')
