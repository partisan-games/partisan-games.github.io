"""Pack the gunner's four generated firing poses beside his unchanged accepted idle pose."""
import hashlib
import json
import runpy
from pathlib import Path
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[4]

def main():
    original = Image.open(ROOT / 'assets/images/armies/nemci/mitraljezac-01.png').convert('RGBA')
    raw = Image.open(HERE / 'fire-generated.png').convert('RGBA')
    sheet = Image.new('RGBA', (252, 81))
    frames = []
    # Align each helmet and bipod; the generator added uneven horizontal padding.
    for index, left in enumerate([32, 501, 968, 1435]):
        frame = raw.crop((left, 300, left + 448, 540))
        frame.putalpha(frame.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
        frame = frame.resize((63, 27), Image.Resampling.NEAREST)
        frames.append(frame)
        sheet.paste(original, (index * 63, 0))
        sheet.paste(frame, (index * 63, 27))
    output = ROOT / 'assets/images/game-ready/vojnici/mitraljezac-sprites.png'
    sheet.save(output)
    strip = Image.new('RGBA', (252, 27), '#3d4332')
    for index, frame in enumerate(frames):
        strip.alpha_composite(frame, (index * 63, 0))
    strip.convert('RGB').save(HERE / 'fire-game-size.png')
    helpers = runpy.run_path(str(HERE.parent / 'tenkovi/prepare.py'))
    helpers['save_gif'](frames, HERE / 'fire.gif', 25)
    death = Image.open(HERE / 'death-generated.png').convert('RGBA')
    death_frames = []
    for index in range(4):
        left = round(index * death.width / 4)
        cell = death.crop((left, 280, round((index + 1) * death.width / 4), 540))
        cell.putalpha(cell.getchannel('A').point(lambda a: 255 if a >= 128 else 0))
        cell = cell.resize((63, 27), Image.Resampling.NEAREST)
        death_frames.append(cell)
        sheet.paste(cell, (index * 63, 54))
    sheet.save(output)
    strip = Image.new('RGBA', (252, 27), '#3d4332')
    for index, frame in enumerate(death_frames):
        strip.alpha_composite(frame, (index * 63, 0))
    strip.convert('RGB').save(HERE / 'death-game-size.png')
    helpers['save_gif'](death_frames, HERE / 'death.gif', 150)
    metadata = {'schemaVersion': 1, 'assets': [{
        'id': 'bunker-machine-gunner', 'image': '../../../game-ready/vojnici/mitraljezac-sprites.png',
        'frame': {'width': 63, 'height': 27, 'columns': 4, 'rows': 3},
        'anchor': {'x': 63, 'y': 27}, 'muzzle': {'x': 1, 'y': 15}, 'facing': 'left',
        'source': 'fire-generated.png', 'reference': '../../nemci/mitraljezac-01.png',
        'sha256': hashlib.sha256(output.read_bytes()).hexdigest(),
        'animations': [
            {'name': 'idle', 'row': 0, 'frameCount': 1, 'duration': 1, 'loop': True},
            {'name': 'fire', 'row': 1, 'frameCount': 4, 'duration': .1, 'loop': False},
            {'name': 'death', 'row': 2, 'frameCount': 4, 'duration': .6, 'loop': False},
        ],
        'notes': 'Accepted 63x27 close-up, not a whole prone body. Idle pixels unchanged. Local origin bottomRight; rotate muzzle offset with the body. Existing Bunker actor and the catalogue share this asset.',
    }]}
    (HERE / 'sprites.json').write_text(json.dumps(metadata, indent=2) + '\n', encoding='utf-8')
    runtime = '''// Generated by assets/images/armies/sources/bunker-gunner/prepare.py.
export default { src: 'game-ready/vojnici/mitraljezac-sprites.png',
  width: 63, height: 27, muzzle: { x: 1, y: 15 }, fireDuration: .1, fireFrames: 4, deathDuration: .6 }
'''
    (ROOT / 'core/actor/soldiers/machineGunnerArt.js').write_text(runtime, encoding='utf-8')
    print('Packed machine gunner: unchanged idle, four firing frames, bottom-right anchor and muzzle.')

if __name__ == '__main__':
    main()
