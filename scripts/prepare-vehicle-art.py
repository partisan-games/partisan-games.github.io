"""Export shared runtime vehicle art from its existing source metadata."""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/images/armies/sources'
metadata_path = SOURCE / 'tenkovi/sprites.json'
metadata = json.loads(metadata_path.read_text(encoding='utf-8'))
usage = json.loads((SOURCE / 'do-trsta/opel-blitz.json').read_text(encoding='utf-8'))
names = {'partizanski-tenk': 'partisanTank', 'nemacki-tenk': 'germanTank'}
assets = {}
for asset in metadata['assets']:
    image = (metadata_path.parent / asset['image']).resolve()
    assets[names[asset['id']]] = {
        'src': image.relative_to(ROOT / 'assets/images').as_posix(),
        'frame': {key: asset['frame'][key] for key in ('width', 'height')},
        'columns': asset['frame']['columns'],
        'clips': {clip['name']: {'row': clip['row'], 'seconds': clip['duration'], 'loop': clip['loop']}
                  for clip in asset['animations']},
    }
body = json.dumps(assets, ensure_ascii=False, indent=2)
body = body[:-2] + ',\n  "opelBlitz": {\n' + \
    f"    ...spriteArt[{json.dumps(usage['assetId'])}],\n" + \
    f"    contentBounds: {json.dumps(usage['render']['sourceContentBounds'])},\n" + \
    f"    size: {json.dumps([usage['collision']['width'], usage['collision']['height']])}\n" + \
    '  }\n}'
def single_quote(match):
    return "'" + json.loads(match.group()).replace('\\', '\\\\').replace("'", "\\'") + "'"

body = re.sub(r'"(?:\\.|[^"\\])*"', single_quote, body)
target = ROOT / 'core/actor/vehicleArt.js'
target.write_text('/** Generated by scripts/prepare-vehicle-art.py from the tank metadata and Opel usage. */\n'
                  "import spriteArt from './spriteArt.js'\n\nexport default " + body + '\n', encoding='utf-8')
print('Exported shared tank art and the existing Opel atlas mapping.')
