"""Build smaller lossless runtime images, retaining the accepted PNG atlases and their metadata.

Run normally after changing game-ready art; --check verifies every mapped image without writing.
"""
import argparse
import hashlib
import io
import json
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
IMAGES = ROOT / 'assets/images'
OUTPUT = IMAGES / 'optimized'
MANIFEST = OUTPUT / 'manifest.json'
MODULE = ROOT / 'core/actor/optimizedImages.js'


def digest(data):
    return hashlib.sha256(data).hexdigest()


def pixels(image):
    return image.convert('RGBA').tobytes()


def verify(entry):
    source = (IMAGES / entry['source']).read_bytes()
    prepared = (IMAGES / entry['runtime']).read_bytes()
    if digest(source) != entry['sourceSha256'] or digest(prepared) != entry['sha256']:
        raise ValueError('Changed image; regenerate: ' + entry['source'])
    with Image.open(io.BytesIO(source)) as original, Image.open(io.BytesIO(prepared)) as runtime:
        if original.size != runtime.size or pixels(original) != pixels(runtime):
            raise ValueError('Pixels differ: ' + entry['source'])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    old = json.loads(MANIFEST.read_text(encoding='utf-8'))['images'] if MANIFEST.exists() else []
    if args.check:
        for entry in old:
            verify(entry)
        expected = module_text(old)
        if MODULE.read_text(encoding='utf-8') != expected:
            raise ValueError('Runtime image map is stale')
        print(f'Checked {len(old)} images: dimensions, every RGBA pixel, hashes and runtime map match')
        return

    cache = {entry['source']: entry for entry in old}
    entries = []
    for i, path in enumerate(sorted((IMAGES / 'armies/game-ready').rglob('*.png')), 1):
        data = path.read_bytes()
        source = path.relative_to(IMAGES).as_posix()
        cached = cache.get(source)
        if cached and cached['sourceSha256'] == digest(data):
            try:
                verify(cached)
                entries.append(cached)
                continue
            except (OSError, ValueError):
                pass
        if len(data) < 4096:
            continue
        with Image.open(io.BytesIO(data)) as image:
            if getattr(image, 'n_frames', 1) != 1 or max(image.size) > 16383 or image.mode not in ('RGB', 'RGBA', 'P', 'L', 'LA'):
                continue
            # Preserve colour profiles; skip non-sRGB gamma metadata rather than changing colour interpretation.
            profile = image.info.get('icc_profile')
            if not profile and 'gamma' in image.info and abs(image.info['gamma'] - .45455) > .0001:
                continue
            encoded = io.BytesIO()
            options = {'icc_profile': profile} if profile else {}
            image.convert('RGBA').save(encoded, format='WEBP', lossless=True, exact=True, method=6, **options)
            prepared = encoded.getvalue()
            if len(data) - len(prepared) < max(512, len(data) * .10):
                continue
            with Image.open(io.BytesIO(prepared)) as decoded:
                if decoded.size != image.size or pixels(decoded) != pixels(image):
                    raise ValueError('Encoder changed pixels: ' + source)
            destination = OUTPUT / Path(source).with_suffix('.webp')
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(prepared)
            entries.append({'source': source, 'runtime': destination.relative_to(IMAGES).as_posix(),
                            'sourceSha256': digest(data), 'sha256': digest(prepared),
                            'originalBytes': len(data), 'bytes': len(prepared), 'size': list(image.size)})
        if i % 20 == 0:
            print(f'Inspected {i} PNG files; {len(entries)} smaller exact copies', flush=True)
    OUTPUT.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps({'format': 'lossless WebP, exact RGBA pixels', 'images': entries}, indent=2) + '\n', encoding='utf-8')
    MODULE.write_text(module_text(entries), encoding='utf-8')
    before = sum(entry['originalBytes'] for entry in entries)
    after = sum(entry['bytes'] for entry in entries)
    print(f'{len(entries)} images: {before:,} -> {after:,} bytes ({(1 - after / before) * 100:.1f}% smaller)')


def module_text(entries):
    mapping = {entry['source']: entry['runtime'] for entry in entries}
    return '// Generated by scripts/prepare-catalog-images.py; PNGs remain the canonical art.\nexport default ' + json.dumps(mapping, indent=2).replace('"', "'") + '\n'


if __name__ == '__main__':
    main()
