"""Mirror the armies art and the 3D models as static galleries; the files stay in their original locations.

Run after adding/removing art or models. --check verifies generated pages and every local link without writes.
"""
import argparse
from dataclasses import dataclass
from html import escape
from html.parser import HTMLParser
import os
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit
from xml.etree import ElementTree

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'art'
MARKER = '<!-- Generated by scripts/build-art-catalog.py; do not edit these pages. -->'


@dataclass(frozen=True)
class Section:
    source: Path
    output: Path
    title: str
    extensions: frozenset
    units: tuple

    def count(self, n):
        """How many there are, the noun in its Serbian form for one, a few, or many."""
        one, few, many = self.units
        last, tens = n % 10, n % 100
        return f'{n} {one if last == 1 and tens != 11 else few if 2 <= last <= 4 and not 12 <= tens <= 14 else many}'


ARMIES = Section(ROOT / 'assets/images/armies', OUTPUT / '2d', '2D',
                 frozenset({'.png', '.gif', '.jpg', '.jpeg', '.webp', '.svg'}), ('slika', 'slike', 'slika'))
MODELS = Section(ROOT / 'assets/models', OUTPUT / '3d', '3D',
                 frozenset({'.fbx', '.glb', '.gltf', '.obj', '.dae'}), ('model', 'modela', 'modela'))


def shows_something(path):
    """An FBX of motion alone, which characters load beside their model, has no mesh to show."""
    if path.suffix.lower() != '.fbx':
        return True
    data = path.read_bytes()
    return b'Geometry' in data and b'Vertices' in data


def url(target, page):
    return quote(Path(os.path.relpath(target, page.parent)).as_posix(), safe='/')


def dimensions(path):
    if path.suffix.lower() == '.svg':
        element = ElementTree.parse(path).getroot()
        box = element.get('viewBox', '').split()
        if len(box) == 4:
            return round(float(box[2])), round(float(box[3]))
        return int(element.get('width', '300').removesuffix('px')), int(element.get('height', '150').removesuffix('px'))
    with Image.open(path) as image:
        return image.size


def copy_button(path):
    return (f'<button type="button" class="copy-name" data-copy-path="{escape(path.relative_to(ROOT).as_posix(), quote=True)}" '
            f'title="Kopiraj relativnu putanju">{escape(path.name)}</button>')


def picture_card(picture, page):
    width, height = dimensions(picture)
    src = url(picture, page)
    return (f'<figure><a href="{src}" target="_blank" rel="noopener">'
            f'<span class="preview"><img src="{src}" loading="lazy" decoding="async" '
            f'width="{width}" height="{height}" alt="{escape(picture.stem, quote=True)}"></span>'
            f'</a><figcaption>{copy_button(picture)}<small>{width} × {height} px '
            f'<span data-copy-status role="status"></span></small></figcaption></figure>')


def model_card(model, page):
    """A model opens in the page's viewer only when chosen; an OBJ brings the materials of the same name."""
    mtl = model.with_suffix('.mtl')
    data = f' data-model="{escape(model.relative_to(MODELS.source).as_posix(), quote=True)}"'
    if model.suffix.lower() == '.obj' and mtl.is_file():
        data += f' data-mtl="{escape(mtl.relative_to(MODELS.source).as_posix(), quote=True)}"'
    size = model.stat().st_size / 1e6
    return (f'<figure><button type="button" class="show-model"{data}><span class="preview">Prikaži u 3D</span></button>'
            f'<figcaption>{copy_button(model)}<small>{size:.1f} MB '
            f'<span data-copy-status role="status"></span></small></figcaption></figure>')


VIEWER = '<div class="model-view"><canvas></canvas><p class="model-status" role="status">Izaberi model.</p></div>'


def build_pages():
    """The catalog's top page and every folder of its 2D and 3D sections with something to show."""
    files, children, section_of = {OUTPUT: []}, {}, {OUTPUT: None}
    for section in (ARMIES, MODELS):
        folders = [section.source, *sorted((p for p in section.source.rglob('*') if p.is_dir()),
                                           key=lambda p: p.as_posix().casefold())]
        for folder in folders:
            section_of[folder] = section
            files[folder] = sorted((p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in section.extensions
                                    and shows_something(p)),
                                   key=lambda p: p.name.casefold())
    totals = dict.fromkeys(files, 0)
    for folder in sorted((f for f in files if f != OUTPUT), key=lambda p: len(p.parts), reverse=True):
        totals[folder] += len(files[folder])
        if folder not in (ARMIES.source, MODELS.source):
            totals[folder.parent] += totals[folder]
    # the armies keep their empty folders, as they always did; a model folder holding only textures is left out
    shown = [OUTPUT, *(f for f in files if section_of[f] is ARMIES or totals[f])]
    for folder in shown[1:]:
        children[folder] = sorted((p for p in folder.iterdir() if p in shown), key=lambda p: p.name.casefold())
    children[OUTPUT] = [ARMIES.source, MODELS.source]

    def page_of(folder):
        section = section_of[folder]
        if not section:
            return OUTPUT / 'index.html'
        return section.output / folder.relative_to(section.source) / 'index.html'

    def title_of(folder):
        section = section_of[folder]
        if not section:
            return 'Art katalog'
        return section.title if folder == section.source else folder.name

    def path_of(folder):
        section = section_of[folder]
        relative = folder.relative_to(section.source).as_posix() if folder != section.source else ''
        return '/'.join(filter(None, [section.output.name, relative]))

    def ancestors(folder):
        chain = []
        while folder != OUTPUT:
            chain.insert(0, folder)
            folder = OUTPUT if folder in (ARMIES.source, MODELS.source) else folder.parent
        return chain

    def models_in(folder):
        """The models of a 3D folder listed in the tree; a folder's only model needs none, as its page shows it at once."""
        return files[folder] if section_of[folder] is MODELS and len(files[folder]) > 1 else []

    def tree(folder, selected, page):
        rows = []
        for child in children[folder]:
            active = ' aria-current="page"' if child == selected else ''
            link = f'<a href="{url(page_of(child), page)}"{active}>{escape(title_of(child))}</a>'
            if children[child] or models_in(child):
                opened = ' open' if child in ancestors(selected) else ''
                link = f'<details{opened}><summary>{link}</summary>{tree(child, selected, page)}</details>'
            rows.append(f'<li data-path="{escape(path_of(child), quote=True)}">{link}</li>')
        # a model's name opens its folder's page showing that model at once
        for model in models_in(folder):
            rows.append(f'<li data-path="{escape(path_of(folder) + "/" + model.name, quote=True)}">'
                        f'<a class="model-link" href="{url(page_of(folder), page)}#{quote(model.name)}">{escape(model.name)}</a></li>')
        return '<ul>' + ''.join(rows) + '</ul>'

    pages = {}
    for folder in shown:
        section, page, title = section_of[folder], page_of(folder), title_of(folder)
        crumbs = [f'<a href="{url(ROOT / "index.html", page)}">Igre</a>']
        for step in [OUTPUT, *ancestors(folder)]:
            crumbs.append(f'<span aria-current="page">{escape(title_of(step))}</span>' if step == folder else
                          f'<a href="{url(page_of(step), page)}">{escape(title_of(step))}</a>')
        navigation = ''.join(f'<li><a href="{url(page_of(child), page)}">{escape(title_of(child))}'
                             f'<small>{section_of[child].count(totals[child])}</small></a></li>' for child in children[folder])
        card = picture_card if section is ARMIES else model_card
        cards = [card(item, page) for item in files[folder]]
        content = f'<nav aria-label="Podfolderi"><ul class="folders">{navigation}</ul></nav>' if children[folder] else ''
        if cards:
            content += (VIEWER if section is MODELS else '') + f'<div class="gallery">{"".join(cards)}</div>'
        elif not children[folder]:
            content += f'<p>U ovom folderu nema {section.units[2]}.</p>'
        viewer = '' if section is not MODELS or not cards else f'''
  <script type="importmap">{{"imports": {{"three": "/libs/three/build/three.module.min.js", "three/": "/libs/three/"}}}}</script>
  <script type="module" src="{url(OUTPUT / 'modelViewer.js', page)}"></script>'''
        pages[page] = f'''<!doctype html>
{MARKER}
<html lang="sr-Latn">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escape(title)} · Art katalog</title>
  <link rel="stylesheet" href="{url(OUTPUT / 'style.css', page)}">
  <script src="{url(OUTPUT / 'navigation.js', page)}" defer></script>{viewer}
</head>
<body>
  <aside class="catalog-list">
    <a class="catalog-home" href="{url(ROOT / 'index.html', page)}">← Početna</a>
    <h2><a href="{url(OUTPUT / 'index.html', page)}">Art katalog</a></h2>
    <label for="folder-search">Pretraži foldere</label>
    <input id="folder-search" type="search" placeholder="npr. nemci motori" autocomplete="off">
    <nav class="tree" aria-label="Folderi arta">{tree(OUTPUT, folder, page)}</nav>
    <p id="no-folders" hidden>Nema rezultata.</p>
  </aside>
  <div class="catalog-content">
    <header><nav aria-label="Putanja">{'<span aria-hidden="true"> / </span>'.join(crumbs)}</nav><h1>{escape(title)}</h1></header>
    <main>{content}</main>
  </div>
</body>
</html>
'''
    count = lambda section: sum(len(files[f]) for f in shown if section_of[f] is section)
    return pages, count(ARMIES), count(MODELS)


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.targets = []

    def handle_starttag(self, tag, attrs):
        self.targets.extend(value for key, value in attrs if key in ('href', 'src'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages, images, models = build_pages()
    obsolete = [p for p in OUTPUT.rglob('index.html') if p not in pages and MARKER in p.read_text(encoding='utf-8')]
    if args.check:
        assert not obsolete, f'Obsolete generated pages: {obsolete}'
        for path, content in pages.items():
            assert path.is_file() and path.read_text(encoding='utf-8') == content, f'Regenerate: {path.relative_to(ROOT)}'
    else:
        for path, content in pages.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
        for path in obsolete:
            path.unlink()
            folder = path.parent
            while folder != OUTPUT and not any(folder.iterdir()):
                folder.rmdir()
                folder = folder.parent
    verified = set()
    for page, content in pages.items():
        links = Links()
        links.feed(content)
        for target in links.targets:
            parsed = urlsplit(target)
            assert not parsed.scheme and not parsed.netloc, (page, target)
            target = os.path.normpath(page.parent / unquote(parsed.path))
            if target in verified:
                continue
            path = Path(target).resolve()
            assert path.is_relative_to(ROOT) and path.is_file(), f'Broken link: {page.relative_to(ROOT)} -> {target}'
            verified.add(target)
    print(f'{"Checked" if args.check else "Generated"} {len(pages)} pages for {images} images and {models} models; '
          'all local links resolve.')


if __name__ == '__main__':
    main()
