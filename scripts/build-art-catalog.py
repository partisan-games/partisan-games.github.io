"""Mirror armies folders as static galleries; images stay in their original locations.

Run after adding/removing art. --check verifies generated pages and every local link without writes.
"""
import argparse
from html import escape
from html.parser import HTMLParser
import os
from pathlib import Path
from urllib.parse import quote, unquote, urlsplit
from xml.etree import ElementTree

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'assets/images/armies'
OUTPUT = ROOT / 'art'
EXTENSIONS = {'.png', '.gif', '.jpg', '.jpeg', '.webp', '.svg'}
MARKER = '<!-- Generated by scripts/build-art-catalog.py; do not edit these pages. -->'


def url(target, page):
    return quote(Path(os.path.relpath(target, page.parent)).as_posix(), safe='/')


def dimensions(path):
    if path.suffix.lower() == '.svg':
        element = ElementTree.parse(path).getroot()
        box = element.get('viewBox', '').split()
        if len(box) == 4:
            return round(float(box[2])), round(float(box[3]))
        return int(element.get('width', '300').removesuffix('px')), int(element.get('height', '150').removesuffix('px'))
    with Image.open(path) as image:
        return image.size


def build_pages():
    folders = [SOURCE, *sorted((p for p in SOURCE.rglob('*') if p.is_dir()), key=lambda p: p.as_posix().casefold())]
    images = {folder: sorted((p for p in folder.iterdir() if p.is_file() and p.suffix.lower() in EXTENSIONS),
                             key=lambda p: p.name.casefold()) for folder in folders}
    totals = {folder: len(items) for folder, items in images.items()}
    for folder in sorted(folders, key=lambda p: len(p.parts), reverse=True):
        if folder != SOURCE:
            totals[folder.parent] += totals[folder]
    children_by_folder = {folder: sorted((p for p in folder.iterdir() if p.is_dir()), key=lambda p: p.name.casefold())
                          for folder in folders}

    def tree(folder, selected, page):
        rows = []
        for child in children_by_folder[folder]:
            relative = child.relative_to(SOURCE)
            active = ' aria-current="page"' if child == selected else ''
            link = f'<a href="{url(OUTPUT / relative / "index.html", page)}"{active}>{escape(child.name)}</a>'
            if children_by_folder[child]:
                opened = ' open' if selected.is_relative_to(child) else ''
                link = f'<details{opened}><summary>{link}</summary>{tree(child, selected, page)}</details>'
            rows.append(f'<li data-path="{escape(relative.as_posix(), quote=True)}">{link}</li>')
        return '<ul>'+''.join(rows)+'</ul>'

    pages = {}
    for folder in folders:
        relative = folder.relative_to(SOURCE)
        page = OUTPUT / relative / 'index.html'
        title = 'Art katalog' if folder == SOURCE else folder.name
        crumbs = [f'<a href="{url(ROOT / "index.html", page)}">Igre</a>']
        current = OUTPUT
        crumbs.append('<span aria-current="page">Art katalog</span>' if folder == SOURCE else
                      f'<a href="{url(OUTPUT / "index.html", page)}">Art katalog</a>')
        for index, part in enumerate(relative.parts):
            current /= part
            crumbs.append(f'<span aria-current="page">{escape(part)}</span>' if index == len(relative.parts) - 1 else
                          f'<a href="{url(current / "index.html", page)}">{escape(part)}</a>')
        children = children_by_folder[folder]
        navigation = ''.join(f'<li><a href="{url(OUTPUT / child.relative_to(SOURCE) / "index.html", page)}">'
                             f'{escape(child.name)}<small>{totals[child]} slika</small></a></li>' for child in children)
        cards = []
        for picture in images[folder]:
            width, height = dimensions(picture)
            src = url(picture, page)
            cards.append(f'<figure><a href="{src}" target="_blank" rel="noopener">'
                         f'<span class="preview"><img src="{src}" loading="lazy" decoding="async" '
                         f'width="{width}" height="{height}" alt="{escape(picture.stem, quote=True)}"></span>'
                         f'</a><figcaption><button type="button" class="copy-name" '
                         f'data-copy-path="{escape(picture.relative_to(ROOT).as_posix(), quote=True)}" title="Kopiraj relativnu putanju">'
                         f'{escape(picture.name)}</button><small>{width} × {height} px '
                         f'<span data-copy-status role="status"></span></small></figcaption></figure>')
        content = (f'<nav aria-label="Podfolderi"><ul class="folders">{navigation}</ul></nav>' if children else '')
        if cards:
            content += f'<div class="gallery">{"".join(cards)}</div>'
        elif not children:
            content += '<p>U ovom folderu nema slika.</p>'
        pages[page] = f'''<!doctype html>
{MARKER}
<html lang="sr-Latn">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>{escape(title)} · Art katalog</title>
  <link rel="stylesheet" href="{url(OUTPUT / 'style.css', page)}">
  <script src="{url(OUTPUT / 'navigation.js', page)}" defer></script>
</head>
<body>
  <aside class="catalog-list">
    <a class="catalog-home" href="{url(ROOT / 'index.html', page)}">← Početna</a>
    <h2><a href="{url(OUTPUT / 'index.html', page)}">Art katalog</a></h2>
    <label for="folder-search">Pretraži foldere</label>
    <input id="folder-search" type="search" placeholder="npr. nemci motori" autocomplete="off">
    <nav class="tree" aria-label="Folderi arta">{tree(SOURCE, folder, page)}</nav>
    <p id="no-folders" hidden>Nema rezultata.</p>
  </aside>
  <div class="catalog-content">
    <header><nav aria-label="Putanja">{'<span aria-hidden="true"> / </span>'.join(crumbs)}</nav><h1>{escape(title)}</h1></header>
    <main>{content}</main>
  </div>
</body>
</html>
'''
    return pages, sum(len(items) for items in images.values())


class Links(HTMLParser):
    def __init__(self):
        super().__init__()
        self.targets = []

    def handle_starttag(self, tag, attrs):
        self.targets.extend(value for key, value in attrs if key in ('href', 'src'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    pages, images = build_pages()
    obsolete = [p for p in OUTPUT.rglob('index.html') if p not in pages and MARKER in p.read_text(encoding='utf-8')]
    if args.check:
        assert not obsolete, f'Obsolete generated pages: {obsolete}'
        for path, content in pages.items():
            assert path.is_file() and path.read_text(encoding='utf-8') == content, f'Regenerate: {path.relative_to(ROOT)}'
    else:
        for path, content in pages.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8')
        for path in obsolete:
            path.unlink()
            folder = path.parent
            while folder != OUTPUT and not any(folder.iterdir()):
                folder.rmdir()
                folder = folder.parent
    verified = set()
    for page, content in pages.items():
        links = Links()
        links.feed(content)
        for target in links.targets:
            parsed = urlsplit(target)
            assert not parsed.scheme and not parsed.netloc, (page, target)
            target = os.path.normpath(page.parent / unquote(parsed.path))
            if target in verified:
                continue
            path = Path(target).resolve()
            assert path.is_relative_to(ROOT) and path.is_file(), f'Broken link: {page.relative_to(ROOT)} -> {target}'
            verified.add(target)
    print(f'{"Checked" if args.check else "Generated"} {len(pages)} pages for {images} images; all local links resolve.')


if __name__ == '__main__':
    main()
